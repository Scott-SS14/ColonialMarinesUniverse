[GenerateTypedNameReferences]
public sealed partial class CMUEmploymentWindow : DefaultWindow
{
    public event Action<bool>? OnSlot;
    public event Action<CMUEmploymentApplyMessage>? OnApply;
    public event Action? OnRefresh;

    private CMUEmploymentState? _state;
    private CMUEmploymentAction _action;
    private readonly Dictionary<ProtoId<AccessLevelPrototype>, CheckBox> _access = new();
    private readonly Font _font;
    private readonly IPrototypeManager _prototypes;
    private readonly SpriteSystem _sprites;
    private readonly List<ProtoId<JobIconPrototype>> _iconIds = new();
    private ProtoId<JobIconPrototype>? _selectedIcon;
    private Color _accent;
    private Color _background;
    private Color _surface;
    private static readonly Color TextPrimary = Color.FromHex("#E1E3DB");
    private static readonly Color TextSecondary = Color.FromHex("#9BA9AB");
    private static readonly Color PanelEdge = Color.FromHex("#3B4A4E");
    private static readonly Color WarningText = Color.FromHex("#DCA286");
    private bool _history;
    private bool _pending;
    private bool _review;
    private bool _updatingState;
    private bool _previewDirty = true;

    public CMUEmploymentWindow()
    {
        RobustXamlLoader.Load(this);
        _font = IoCManager.Resolve<IResourceCache>().GetFont("/Fonts/RobotoMono/RobotoMono-Regular.ttf", 12);
        _prototypes = IoCManager.Resolve<IPrototypeManager>();
        _sprites = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SpriteSystem>();
        InitializeHardware(IoCManager.Resolve<IResourceCache>());
        InitializePresentation();
        InitializeColony();
        InitializePayroll();
        InitializeOffices();
        Title = Loc.GetString("cmu-employment-window");
        OperationsCaption.Text = Loc.GetString("cmu-employment-operations");
        ReaderCaption.Text = Loc.GetString("cmu-employment-readers");
        ReaderHint.Text = Wrap(Loc.GetString("cmu-employment-reader-hint"), 19);
        NameCaption.Text = Loc.GetString("cmu-employment-name");
        TitleCaption.Text = Loc.GetString("cmu-employment-title");
        PresetCaption.Text = Loc.GetString("cmu-employment-presets");
        AccessCaption.Text = Loc.GetString("cmu-employment-access");
        AccessSearch.PlaceHolder = Loc.GetString("cmu-employment-search");
        ClearAccessButton.Text = Loc.GetString("cmu-employment-clear");
        Iff.Text = Loc.GetString("cmu-employment-iff");
        IconCaption.Text = Loc.GetString("cmu-employment-job-icon");
        IconChoices.ToolTip = Loc.GetString("cmu-employment-job-icon-hint");
        IffHint.Text = Wrap(Loc.GetString("cmu-employment-iff-hint"), 58);
        Confirm.Text = Loc.GetString("cmu-employment-confirm");
        HireButton.Text = Loc.GetString("cmu-employment-hire");
        EditButton.Text = Loc.GetString("cmu-employment-edit");
        TerminateButton.Text = Loc.GetString("cmu-employment-terminate");
        HistoryButton.Text = Loc.GetString("cmu-employment-history");
        RefreshButton.Text = Loc.GetString("cmu-employment-refresh");
        CancelButton.Text = Loc.GetString("cmu-employment-cancel");
        OperatorSlot.OnPressed += _ => OnSlot?.Invoke(true);
        TargetSlot.OnPressed += _ => OnSlot?.Invoke(false);
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        HireButton.OnPressed += _ => SetAction(CMUEmploymentAction.Hire);
        EditButton.OnPressed += _ => SetAction(CMUEmploymentAction.Edit);
        TerminateButton.OnPressed += _ => SetAction(CMUEmploymentAction.Terminate);
        HistoryButton.OnPressed += _ =>
        {
            _colonyPage = 0;
            _history = !_history;
            _review = false;
            Confirm.Pressed = false;
            UpdateActions();
        };
        CancelButton.OnPressed += _ => ResetDraft();
        ApplyButton.OnPressed += _ => Submit();
        Confirm.OnToggled += _ => UpdateActions();
        Iff.OnToggled += _ => InvalidateDraft();
        TitleField.OnTextChanged += _ => InvalidateDraft();
        NameField.OnTextChanged += _ => InvalidateDraft();
        AccessSearch.OnTextChanged += _ => FilterAccess();
        IconChoices.OnItemSelected += args =>
        {
            if (args.Id < 0 || args.Id >= _iconIds.Count)
                return;
            IconChoices.SelectId(args.Id);
            _selectedIcon = _iconIds[args.Id];
            UpdateIconPreview();
            InvalidateDraft();
        };
        ClearAccessButton.OnPressed += _ =>
        {
            foreach (var check in _access.Values)
                check.Pressed = false;
            InvalidateDraft();
        };
        foreach (var button in new[] { HireButton, EditButton, TerminateButton, HistoryButton,
                     OperatorSlot, TargetSlot, RefreshButton, CancelButton, ApplyButton, ClearAccessButton })
            BindButton(button);
    }

    public void UpdateState(CMUEmploymentState state)
    {
        if (TryUpdateColonyOnly(state))
            return;
        var previous = _state;
        _updatingState = true;
        _previewDirty = true;
        _state = state;
        _pending = false;
        _payrollPending = false;
        _accent = state.Accent ?? Color.FromHex(state.Theme switch
        {
            CMUEmploymentTheme.Govfor => "#9CBF6E",
            CMUEmploymentTheme.Colony => "#3FE05A",
            _ => "#FFB547",
        });
        _background = state.Background ?? Color.FromHex(state.Theme switch
        {
            CMUEmploymentTheme.Govfor => "#090D07",
            CMUEmploymentTheme.Colony => "#060F0A",
            _ => "#120A02",
        });
        _surface = state.Surface ?? Color.FromHex(state.Theme switch
        {
            CMUEmploymentTheme.Govfor => "#151E10",
            CMUEmploymentTheme.Colony => "#0B2115",
            _ => "#291A08",
        });
        _background = Blend(Color.FromHex("#10171B"), _background, 0.3f);
        _surface = Blend(Color.FromHex("#202B30"), _surface, 0.25f);
        Brand.Text = Loc.GetString(state.Theme switch
        {
            CMUEmploymentTheme.Govfor => "cmu-employment-brand-govfor",
            CMUEmploymentTheme.Colony => "cmu-employment-brand-colony",
            _ => "cmu-employment-brand-weyland",
        });
        if (!string.IsNullOrEmpty(state.Brand))
            Brand.Text = Loc.GetString("cmu-employment-brand-selected", ("name", state.Brand));
        TerminalFooter.Text = Wrap(Loc.GetString(state.Theme switch
        {
            CMUEmploymentTheme.Govfor => "cmu-employment-footer-govfor",
            CMUEmploymentTheme.Colony => "cmu-employment-footer-colony",
            _ => "cmu-employment-footer-weyland",
        }), 19);
        Heading.Text = state.Heading;
        Status.Text = Loc.GetString(!state.Powered ? "cmu-employment-offline"
            : state.Printing ? "cmu-employment-printing"
            : state.Authenticated ? "cmu-employment-authenticated" : "cmu-employment-locked",
            ("name", state.OperatorName));
        Status.ToolTip = Status.Text;
        OperatorSlot.Text = Loc.GetString(state.OperatorCardInserted
            ? "cmu-employment-reader-operator-eject" : "cmu-employment-reader-operator");
        TargetSlot.Text = Loc.GetString(state.Target != null
            ? "cmu-employment-reader-target-eject" : "cmu-employment-reader-target");
        TargetSlot.ToolTip = state.TargetName;
        CurrentTitle.Text = Loc.GetString("cmu-employment-current-title", ("title", state.JobTitle));
        CurrentTitle.ToolTip = CurrentTitle.Text;

        _iconIds.Clear();
        IconChoices.Clear();
        foreach (var option in state.JobIcons)
        {
            IconChoices.AddItem(option.Name, _iconIds.Count);
            _iconIds.Add(option.Id);
        }
        IconRow.Visible = _iconIds.Count > 0;

        _access.Clear();
        AccessList.RemoveAllChildren();
        foreach (var restricted in new[] { false, true })
        {
            var options = state.Options.Where(option => option.Restricted == restricted).ToList();
            if (options.Count == 0)
                continue;
            AccessList.AddChild(new Label
            {
                Text = Loc.GetString(restricted ? "cmu-employment-access-sensitive" : "cmu-employment-access-standard"),
                Margin = new Thickness(0, 6, 0, 2),
            });
            foreach (var option in options)
            {
                var check = new CheckBox
                {
                    Text = option.Name,
                    ToolTip = option.Restricted
                        ? Loc.GetString("cmu-employment-sensitive-hint", ("name", option.Name)) : option.Name,
                };
                check.OnToggled += _ => InvalidateDraft();
                _access.Add(option.Id, check);
                AccessList.AddChild(check);
            }
        }
        Presets.RemoveAllChildren();
        foreach (var preset in state.Presets)
        {
            var button = new Button { Text = preset.Name };
            BindButton(button);
            button.OnPressed += _ =>
            {
                TitleField.Text = preset.Title;
                foreach (var (tag, check) in _access)
                    check.Pressed = preset.Access.Contains(tag);
                if (preset.JobIcon is { } icon && _iconIds.Contains(icon))
                {
                    _selectedIcon = icon;
                    IconChoices.SelectId(_iconIds.IndexOf(icon));
                    UpdateIconPreview();
                }
                InvalidateDraft();
            };
            Presets.AddChild(button);
        }
        HistoryList.RemoveAllChildren();
        foreach (var entry in state.History.AsEnumerable().Reverse())
            HistoryList.AddChild(new Label { Text = entry, ToolTip = entry, ClipText = true });
        if (state.History.Count == 0)
            HistoryList.AddChild(new Label { Text = Loc.GetString("cmu-employment-history-empty") });
        ApplyTheme(Bezel);
        Bezel.PanelOverride = Box(Color.FromHex("#242725"), _accent, 2);
        Screen.PanelOverride = Box(_background, _accent, 1);
        foreach (var panel in new[] { NavigationPanel, IdentityPanel, PresetPanel, AccessPanel, HistoryFrame, ReviewPanel })
            panel.PanelOverride = Box(_surface, PanelEdge, 1);
        HeaderPanel.PanelOverride = Box(Blend(_surface, _accent, 0.08f), PanelEdge, 1);
        IconChoices.StyleBoxOverride = Box(_background, _accent.WithAlpha(0.5f), 1);
        Brand.FontColorOverride = TextPrimary;
        Heading.FontColorOverride = TextSecondary;
        foreach (var caption in new[] { NameCaption, TitleCaption, IconCaption, PresetCaption, AccessCaption })
            caption.FontColorOverride = TextSecondary;
        IffHint.FontColorOverride = TextSecondary;
        Review.FontColorOverride = WarningText;
        CurrentTitle.FontColorOverride = TextSecondary;
        Status.FontColorOverride = !state.Powered ? WarningText
            : state.Printing ? BusyLamp : state.Authenticated ? _accent : TextSecondary;
        ResetDraft();
        FilterAccess();
        UpdateHardware();
        _updatingState = false;
        UpdatePresentation();
        UpdateReceipt(previous);
    }

    private static StyleBoxFlat Box(Color background, Color border, int width) => new()
    {
        BackgroundColor = background,
        BorderColor = border,
        BorderThickness = new Thickness(width),
    };

    private static Color Blend(Color a, Color b, float amount) => new(
        a.R + (b.R - a.R) * amount,
        a.G + (b.G - a.G) * amount,
        a.B + (b.B - a.B) * amount,
        1f);

    private void BindButton(Button button)
    {
        button.OnMouseEntered += _ =>
        {
            if (!button.Disabled)
                button.StyleBoxOverride = Box(Blend(_surface, _accent, 0.12f), _accent.WithAlpha(0.65f), 1);
        };
        button.OnMouseExited += _ => StyleButton(button);
    }

    private void StyleButton(Button button)
    {
        var selected = _colonyPage == 0 && (button == HireButton && !_history && _action == CMUEmploymentAction.Hire
            || button == EditButton && !_history && _action == CMUEmploymentAction.Edit
            || button == TerminateButton && !_history && _action == CMUEmploymentAction.Terminate
            || button == HistoryButton && _history
            || button == PreviewButton && _review)
            || button == PersonnelApp && _colonyPage == 0 || button == ManifestApp && _colonyPage == 1
            || button == CommunicationsApp && _colonyPage == 2 || button == PayrollApp && _colonyPage == 3
            || button == OfficeRequestsApp && _colonyPage == 4 || button == OfficeServicesApp && _colonyPage == 5
            || button == OfficeJailApp && _colonyPage == 6;
        var destructive = button == TerminateButton || button == ApplyButton && _action == CMUEmploymentAction.Terminate;
        var color = destructive ? WarningText : _accent;
        var prominent = selected || button == ApplyButton && !button.Disabled;
        button.StyleBoxOverride = Box(prominent ? Blend(_surface, color, 0.16f) : _background,
            (prominent ? color : PanelEdge).WithAlpha(button.Disabled ? 0.35f : 0.8f), 1);
        button.Label.FontOverride = _font;
        button.Label.FontColorOverride = (prominent || destructive ? color : TextPrimary).WithAlpha(button.Disabled ? 0.35f : 1f);
    }

    private void ApplyTheme(Control control)
    {
        if (ReferenceEquals(control, _manifest))
            return;
        if (control is Label label)
        {
            label.FontOverride = _font;
            label.FontColorOverride = TextPrimary;
        }
        if (control is LineEdit field)
            field.StyleBoxOverride = Box(_background, PanelEdge, 1);
        foreach (var child in control.Children)
            ApplyTheme(child);
        if (control is Button button)
            StyleButton(button);
    }

    private void SetAction(CMUEmploymentAction action)
    {
        _colonyPage = 0;
        _action = action;
        _history = false;
        _review = false;
        _previewDirty = true;
        if (!_updatingState)
            _draftEdited = true;
        Confirm.Pressed = false;
        UpdateActions();
    }

    private void ResetDraft()
    {
        if (_state is not { } state)
            return;

        NameField.Text = state.TargetName;
        TitleField.Text = state.JobTitle;
        Iff.Pressed = state.HasIff;
        _selectedIcon = _iconIds.Contains(state.JobIcon) ? state.JobIcon : state.DefaultJobIcon;
        if (_selectedIcon is { } icon)
        {
            var index = _iconIds.IndexOf(icon);
            if (index >= 0)
                IconChoices.SelectId(index);
        }
        UpdateIconPreview();
        foreach (var (tag, check) in _access)
            check.Pressed = state.CurrentAccess.Contains(tag);
        InvalidateDraft();
        _draftEdited = false;
        UpdatePresentation();
    }

    private void InvalidateDraft()
    {
        _previewDirty = true;
        if (!_updatingState)
            _draftEdited = true;
        Confirm.Pressed = false;
        UpdateActions();
    }

    private void FilterAccess()
    {
        var query = AccessSearch.Text.Trim();
        foreach (var (tag, check) in _access)
            check.Visible = query.Length == 0 || (check.Text?.Contains(query, StringComparison.OrdinalIgnoreCase) ?? false)
                || tag.Id.Contains(query, StringComparison.OrdinalIgnoreCase);
    }

    private void UpdateIconPreview()
    {
        IconPreview.Texture = _selectedIcon is { } icon && _prototypes.TryIndex(icon, out var definition)
            ? _sprites.Frame0(definition.Icon) : null;
    }

    private void UpdateActions()
    {
        if (_state is not { } state)
            return;
        var active = state.Powered && state.Authenticated && state.Target != null && !_pending && !state.Printing;
        var editing = active && !_history && _action != CMUEmploymentAction.Terminate;
        Workspace.Visible = !_history && !_review;
        DossierFrame.Visible = _review && !_history;
        HistoryFrame.Visible = _history;
        TitleField.Editable = editing;
        NameField.Editable = editing && state.Blank;
        Iff.Disabled = !editing;
        IconChoices.Disabled = !editing;
        ClearAccessButton.Disabled = !editing;
        foreach (var check in _access.Values)
            check.Disabled = !editing;
        foreach (var child in Presets.Children)
        {
            if (child is Button button)
                button.Disabled = !editing;
        }
        HireButton.Disabled = !active;
        EditButton.Disabled = !active || !state.LocalEmployee;
        TerminateButton.Disabled = !active || !state.LocalEmployee;
        Confirm.Disabled = !active || _history;
        CancelButton.Disabled = !active || _history;
        var validText = !string.IsNullOrWhiteSpace(TitleField.Text) && TitleField.Text.Trim().Length <= 40
            && (!state.Blank || !string.IsNullOrWhiteSpace(NameField.Text) && NameField.Text.Trim().Length <= 64);
        ApplyButton.Disabled = !active || _history || !Confirm.Pressed
            || _action != CMUEmploymentAction.Terminate && !validText
            || _action != CMUEmploymentAction.Hire && !state.LocalEmployee;
        ApplyButton.Text = Loc.GetString(_action switch
        {
            CMUEmploymentAction.Hire => "cmu-employment-apply-hire",
            CMUEmploymentAction.Edit => "cmu-employment-apply-edit",
            _ => "cmu-employment-apply-terminate",
        });
        AccessCount.Text = Loc.GetString("cmu-employment-access-count", ("count", _access.Values.Count(check => check.Pressed)));
        Review.Text = Wrap(Loc.GetString(_action == CMUEmploymentAction.Terminate
            ? "cmu-employment-review-terminate" : "cmu-employment-review-replace"), 58);
        foreach (var button in new[] { HireButton, EditButton, TerminateButton, HistoryButton,
                     OperatorSlot, TargetSlot, RefreshButton, CancelButton, ApplyButton, ClearAccessButton })
            StyleButton(button);
        foreach (var child in Presets.Children)
        {
            if (child is Button button)
                StyleButton(button);
        }
        UpdatePresentation();
        UpdateColony();
        UpdateOffices();
    }

    private static string Wrap(string text, int columns)
    {
        var lines = new List<string>();
        var line = string.Empty;
        foreach (var word in text.Split(' '))
        {
            if (line.Length > 0 && line.Length + word.Length + 1 > columns)
            {
                lines.Add(line);
                line = string.Empty;
            }
            line = line.Length == 0 ? word : line + " " + word;
        }
        if (line.Length > 0)
            lines.Add(line);
        return string.Join("\n", lines);
    }

    private void Submit()
    {
        if (_state is not { Target: { } card } state || !Confirm.Pressed || _pending || ApplyButton.Disabled)
            return;
        var tags = new List<ProtoId<AccessLevelPrototype>>();
        foreach (var (tag, check) in _access)
        {
            if (check.Pressed)
                tags.Add(tag);
        }
        _pending = true;
        UpdateActions();
        OnApply?.Invoke(new(card, state.Revision, _action, TitleField.Text, NameField.Text, tags, Iff.Pressed, true, _selectedIcon));
    }
}
